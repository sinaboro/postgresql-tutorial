SET client_min_messages = warning;
DROP TABLE IF EXISTS reviews, order_items, orders, products, categories,
                     customers, employees, departments CASCADE;
RESET client_min_messages;

-- 부서
CREATE TABLE departments (
    dept_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL UNIQUE,
    location   VARCHAR(50)
);

-- 직원 (manager_id 로 자기 자신을 참조하는 계층 구조)
CREATE TABLE employees (
    emp_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50)   NOT NULL,
    dept_id    INTEGER       REFERENCES departments (dept_id),
    manager_id INTEGER       REFERENCES employees (emp_id),
    job_title  VARCHAR(50)   NOT NULL,
    salary     NUMERIC(10,0) NOT NULL CHECK (salary > 0),   -- 연봉(만원)
    hire_date  DATE          NOT NULL,
    email      VARCHAR(100)  UNIQUE
);

-- 고객
CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    email       VARCHAR(100) NOT NULL UNIQUE,
    phone       VARCHAR(20),
    city        VARCHAR(30)  NOT NULL,
    grade       VARCHAR(10)  NOT NULL DEFAULT 'BRONZE'
                CHECK (grade IN ('BRONZE', 'SILVER', 'GOLD', 'VIP')),
    birth_date  DATE,
    joined_at   TIMESTAMP    NOT NULL DEFAULT now()
);

-- 상품 분류 (parent_id 로 상위 분류를 참조하는 트리 구조)
CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    parent_id   INTEGER REFERENCES categories (category_id)
);

-- 상품
CREATE TABLE products (
    product_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER       NOT NULL REFERENCES categories (category_id),
    name        VARCHAR(100)  NOT NULL,
    price       NUMERIC(10,0) NOT NULL CHECK (price >= 0),   -- 원
    stock       INTEGER       NOT NULL DEFAULT 0 CHECK (stock >= 0),
    is_active   BOOLEAN       NOT NULL DEFAULT true,
    attrs       JSONB,                                        -- 브랜드, 색상 등 부가 속성
    created_at  TIMESTAMP     NOT NULL DEFAULT now()
);

-- 주문
CREATE TABLE orders (
    order_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER     NOT NULL REFERENCES customers (customer_id),
    emp_id      INTEGER     REFERENCES employees (emp_id),   -- 담당 직원 (온라인 주문은 NULL)
    order_date  TIMESTAMP   NOT NULL,
    status      VARCHAR(10) NOT NULL
                CHECK (status IN ('PENDING', 'PAID', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    ship_city   VARCHAR(30) NOT NULL
);

-- 주문 상세 (주문 1건에 여러 상품)
CREATE TABLE order_items (
    order_id    INTEGER       NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    product_id  INTEGER       NOT NULL REFERENCES products (product_id),
    quantity    INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(10,0) NOT NULL CHECK (unit_price >= 0),  -- 주문 당시 판매가
    PRIMARY KEY (order_id, product_id)
);

-- 상품 리뷰
CREATE TABLE reviews (
    review_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  INTEGER   NOT NULL REFERENCES products (product_id),
    customer_id INTEGER   NOT NULL REFERENCES customers (customer_id),
    rating      SMALLINT  NOT NULL CHECK (rating BETWEEN 1 AND 5),
    content     TEXT,
    created_at  TIMESTAMP NOT NULL
);

COMMENT ON TABLE  orders           IS '고객 주문 헤더';
COMMENT ON COLUMN employees.salary IS '연봉(단위: 만원)';
